"""Builds QRINGS_REPORT.md from results2.json (and meta.json). python tools/qrings/make_report.py results2.json [before.json]"""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze import verdict
HERE = os.path.dirname(os.path.abspath(__file__))
STEP = {'gandrick': '3', 'ironhill': '5', 'mines': '6', 'overseer': '6 (side)', 'escape': '7', 'pass': '8', 'scoria': '9', 'kh_seal': '10', 'yar2': '14', 'kh_sea': '15', 'yar3': '16', 'yar4': '17', 'yar5': '18', 'yar6': '19', 'yar7': '20',
        'vq1': '21', 'vq2': '22', 'vq3': '23', 'vq4': '24', 'vq5': '25', 'kg0': '26', 'kg1': '27', 'kg2': '28', 'kg3': '29', 'kg4': '30', 'sd2': '31', 'vq6': '32', 'oq0': '33', 'oa1': '35', 'oa2': '36', 'oa3': '36', 'oa4': '36', 'oa6': '36', 'oa7': '36',
        'oa5': '37', 'oa8': '38', 'oa9': '39', 'ad1': '40', 'ad2': '41', 'ad3': '42', 'ad4': '43', 'hc1': '44', 'hc2': '45', 'hgb1': '49', 'hgb2': '50', 'hgb3': '51', 'hgb4': '52', 'hgrescue': '53', 'dh1': '54', 'dh2': '55', 'dh3': '56',
        'dq11': '58', 'dq12': '59', 'hgsph': '60', 'bsw1': '62', 'wk1': '65', 'wk2': '67', 'wk3': '68', 'mq1': 'monastery', 'mq2': 'monastery', 'shell': 'branch'}
for i in range(1, 9): STEP['sg%d' % i] = '34'
for i in range(1, 8): STEP['kh_c%d' % i] = '9 (Khemetra maps)'
for i in range(1, 6): STEP['gyq%d' % i] = 'Graveyard %d (L84-87)' % i
for i in range(1, 10): STEP['wwq%d' % i] = 'Witch %d' % i
res = json.load(open(sys.argv[1]))['res']
meta = json.load(open(HERE + '/meta.json')) if os.path.exists(HERE + '/meta.json') else {}
yn = lambda b: 'yes' if b else 'NO'
by = {}
for r in res: by.setdefault(r['id'], {})[r['stage']] = r
rows, fails = [], []
for id, st in by.items():
    m = meta.get(id) or {}
    v = {k: verdict(r) for k, r in st.items()}
    lv = lambda k: ', '.join(sorted({(x['name'] or str(x['lvl'])) + ' (%d)' % x['lvl'] for x in (m.get(k) or [])})[:3]) if m else ''
    notes = []
    for k in ('give', 'act', 'ready'):
        for n in v[k]['notes'][:2]: notes.append('%s: %s' % (k, n))
        if not (v[k]['ring'] and v[k]['place'] and v[k]['world']): fails.append((id, k, v[k]['notes']))
    place = all(v[k]['place'] for k in v); world = all(v[k]['world'] for k in v)
    rows.append('| %s | %s: %s | %s | %s | %s | %s | %s | %s | %s |' % (STEP.get(id, '?'), id, m.get('title', ''), lv('act'), m.get('giver') or m.get('who', ''),
                yn(v['give']['ring']), yn(v['act']['ring']), yn(place), yn(world), '; '.join(notes)[:200] or 'ok'))
out = ['# Quest rings report', '', 'Generated by tools/qrings/make_report.py from the harness run (tools/qrings/run2.py). One row per quest of the main line (and the graveyard, witch, monastery and shell chains).',
       'Each quest was set to each stage in turn (not taken, active, ready to hand in), clicked in the quest panel (the real handler `qrow_<id>`; untaken quests go through `questShow`, since the panel lists only taken quests) and the local map was read for the focus ring.', '',
       '| Step | Quest | Level of the work | Giver | Ring when not taken | Ring while active | Correct place | World map ring (other levels) | Notes |', '|---|---|---|---|---|---|---|---|---|'] + rows
out += ['', '## Summary', '', 'Quests checked: %d. Stage checks with a failure: %d of %d.' % (len(by), len(fails), len(res)), '']
for id, k, n in fails: out.append('- %s (%s): %s' % (id, k, '; '.join(n[:2])))
open(HERE + '/QRINGS_REPORT.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('failures', len(fails), 'of', len(res))
